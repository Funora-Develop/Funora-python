"""Проверки утверждений об отсутствии.

ЗАЧЕМ ЭТОТ НАБОР. Сверка контракта с независимой реализацией того же протокола
нашла около сорока мест, где спецификация утверждала «этого на странице нет», а
наблюдение лежало в наших же записях.

У всех сорока один механизм, и он не про небрежность. Снимок пересняли - он стал
богаче, - а утверждение об отсутствии осталось прежним, и перечитывать его было
некому.

Ворота проекта сторожат, чтобы объявленное было НАПИСАНО. Обратного они не
сторожили: чтобы утверждение об отсутствии не пережило наблюдение, которое его
опровергает.

КАК ЭТОТ НАБОР ЭТО ЛОВИТ. Каждое утверждение называет снимки, на которых
проверено, и отпечаток каждого. Проверка считает отпечатки заново; разошлись -
падает ИМЕННО на том утверждении, которое надо перечитать.

Отпечаток, а не дата: дата снимка не меняется при выгрузке из хранилища истории,
а время правки файла меняется от одного git checkout.

ЧЕГО НАБОР НЕ ДЕЛАЕТ. Он не проверяет, что утверждение ВЕРНО - для этого нужен
человек, читающий снимок. Он делает единственное: не даёт утверждению пережить
пересъёмку молча.
"""

from __future__ import annotations

import os
from hashlib import sha256
from pathlib import Path
from typing import Any, Final

import pytest
import yaml

ROOT: Final[Path] = Path(__file__).resolve().parent.parent

#: Сколько знаков отпечатка хранится. Восьми хватает: файлов у нас четыре
#: десятка, и случайное совпадение здесь означало бы не пропущенную ошибку, а
#: невероятное везение.
_DIGEST_CHARS: Final[int] = 16


def _spec_dir() -> Path:
    """Находит хранилище спецификации.

    Возвращает:
        Path: Каталог спецификации.
    """
    named = os.environ.get("FUNORA_SPEC_DIR")
    if named:
        return Path(named)
    return ROOT.parent / "Funora-spec"


def _claims() -> dict[str, Any]:
    """Читает реестр утверждений об отсутствии.

    Возвращает:
        dict[str, Any]: Утверждения по имени.
    """
    path = _spec_dir() / "spec/conformance/absence-claims.yaml"
    doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    return doc["claims"]


def _digest(path: Path) -> str:
    """Считает отпечаток снимка.

    Аргументы:
        path (Path): Путь снимка.

    Возвращает:
        str: Начало шестнадцатеричного отпечатка.
    """
    return sha256(path.read_bytes()).hexdigest()[:_DIGEST_CHARS]


def test_the_registry_is_not_empty() -> None:
    """Требует, чтобы реестр не опустел молча.

    Пустой реестр прошёл бы все прочие проверки этого набора: цикл по нулю
    записей не падает никогда. Проверка на пустоту стоит первой именно поэтому.

    Возвращает:
        None
    """
    claims = _claims()
    assert len(claims) >= 6, f"утверждений в реестре {len(claims)} - реестр опустел"


@pytest.mark.parametrize("name", sorted(_claims()))
def test_every_claim_names_a_snapshot_that_exists(name: str) -> None:
    """Требует, чтобы каждое утверждение называло существующий снимок.

    Утверждение без снимка проверить нечем, и от выдумки оно неотличимо ровно
    так же, как правило извлечения без ссылки на снимок.

    Аргументы:
        name (str): Имя утверждения.

    Возвращает:
        None
    """
    claim = _claims()[name]
    checked = claim.get("checked_against") or []
    assert checked, f"{name}: не назван ни один снимок"

    for entry in checked:
        path = ROOT / entry["file"]
        assert path.is_file(), f"{name}: снимок {entry['file']} не найден"


@pytest.mark.parametrize("name", sorted(_claims()))
def test_no_claim_outlives_a_re_taken_snapshot(name: str) -> None:
    """ГЛАВНАЯ ПРОВЕРКА: утверждение не переживает пересъёмку снимка.

    Это и есть тот механизм, который дал сорок ложных записей. Снимок
    пересняли, он стал богаче, а утверждение об отсутствии осталось прежним.

    Отпечаток разошёлся - значит снимок другой, и утверждение надо перечитать
    ГЛАЗАМИ, а не обновить отпечаток не глядя.

    Аргументы:
        name (str): Имя утверждения.

    Возвращает:
        None
    """
    claim = _claims()[name]
    for entry in claim.get("checked_against") or []:
        path = ROOT / entry["file"]
        actual = _digest(path)
        stored = entry.get("digest") or ""

        assert stored, (
            f"{name}: у снимка {entry['file']} не записан отпечаток. "
            f"Он равен {actual!r} - но впишите его ТОЛЬКО перечитав снимок и "
            "убедившись, что утверждение всё ещё верно"
        )
        assert stored == actual, (
            f"{name}: снимок {entry['file']} пересняли - отпечаток был {stored!r}, "
            f"стал {actual!r}.\n\n"
            f"УТВЕРЖДЕНИЕ: {str(claim.get('asserts', '')).strip()[:200]}\n\n"
            "Перечитайте снимок и решите, верно ли оно ещё. Обновить отпечаток "
            "не глядя значит завести сорок первую ложную запись"
        )


@pytest.mark.parametrize("name", sorted(_claims()))
def test_a_standing_claim_rests_on_a_positive_marker(name: str) -> None:
    """ГЛАВНАЯ ПРОВЕРКА ВТОРАЯ: действующее утверждение стоит на признаке.

    Правило проекта: отсутствие объявляется ТОЛЬКО по положительному признаку.
    «Мы этого не нашли» - не признак: не нашли и на однородном снимке, где
    признака нет по построению. Ровно так три недели жила запись про показ лота.

    Поэтому у каждого действующего утверждения обязано быть сказано, что именно
    в снимке ВИДНО, а не чего в нём не нашлось.

    Аргументы:
        name (str): Имя утверждения.

    Возвращает:
        None
    """
    claim = _claims()[name]
    if claim.get("verdict") != "standing":
        return

    marker = str(claim.get("positive_marker") or "").strip()
    assert marker, (
        f"{name}: действующее утверждение об отсутствии без положительного признака. "
        "Скажите, что в снимке ВИДНО, а не чего в нём не нашлось"
    )
    assert len(marker) > 80, f"{name}: признак слишком короток, чтобы что-то значить"

    refute = str(claim.get("what_would_refute_it") or "").strip()
    assert refute, (
        f"{name}: не сказано, какое наблюдение утверждение опровергнет. "
        "Утверждение, которое нечем опровергнуть, - не утверждение"
    )


@pytest.mark.parametrize("name", sorted(_claims()))
def test_a_refuted_claim_says_what_refuted_it(name: str) -> None:
    """Требует, чтобы снятое утверждение называло, чем именно снято.

    Запись о снятом утверждении остаётся не ради истории. Она отвечает на
    вопрос, который иначе задают заново: почему тут когда-то стояло обратное.

    Аргументы:
        name (str): Имя утверждения.

    Возвращает:
        None
    """
    claim = _claims()[name]
    if claim.get("verdict") != "refuted":
        return

    assert str(claim.get("refuted_by") or "").strip(), f"{name}: не сказано, чем снято"
    assert str(claim.get("lived_for") or "").strip(), (
        f"{name}: не сказано, сколько утверждение прожило. Срок здесь не укор, а "
        "мера того, насколько дорого обходится непроверенное отсутствие"
    )


def test_every_verdict_is_one_of_the_two_known() -> None:
    """Требует, чтобы вердикт был из перечня.

    Незнакомый вердикт молча пропустил бы обе проверки выше: они обе
    сравнивают его со своим значением и на чужом ничего не делают.

    Возвращает:
        None
    """
    for name, claim in _claims().items():
        assert claim.get("verdict") in {"standing", "refuted"}, (
            f"{name}: вердикт {claim.get('verdict')!r} неизвестен"
        )
