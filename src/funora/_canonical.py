"""Каноническая сериализация JSON.

Правила объявлены в docs/canonical-json.md спецификации и до сих пор не
выполнялись ни одной строкой кода. Файл состояния при этом штамповал в себя
`canonical_form_version` - то есть утверждал про себя то, чего никто не делал:
он писался с пробелами после двоеточия и запятой, с числами с плавающей точкой
и без нормализации Unicode.

Зачем форма нужна. Отпечаток события - ключ идемпотентности, общий для шести
реализаций. Если байты, от которых считается хэш, зависят от того, каким
сериализатором пользуется язык, то две реализации дадут одному событию два
разных идентификатора, и гашение повторов у человека, подключившего обе, не
сработает ни разу. Для обработчика выдачи это выданный дважды товар.

Форма нарочно узкая. Она не универсальный сериализатор и не должна им быть:
всё, чего она не умеет выразить однозначно, она отвергает вслух. Число с
плавающей точкой не имеет единственного десятичного вида, поэтому запрещено;
ключ не-строка не имеет порядка по кодовым точкам, поэтому запрещён.
"""

from __future__ import annotations

import json
import math
import unicodedata
from typing import Any, Final

from .errors import ValidationError

__all__ = [
    "canonical_dumps",
    "canonical_normalize",
]

#: Разделители без единого незначащего пробела.
#:
#: Правило 5. Умолчание Python - ``(", ", ": ")``, и именно оно делало файл
#: состояния неканоническим, оставаясь незаметным: JSON от этого не перестаёт
#: разбираться, расходятся только байты - то есть ровно то, от чего берут хэш.
_SEPARATORS: Final[tuple[str, str]] = (",", ":")


def canonical_normalize(text: str) -> str:
    """Приводит строку к форме Unicode NFC.

    Правило 2. Одна и та же буква записывается по-разному: «ё» бывает одним
    знаком и парой «е» с диакритикой. Глазами не отличить, байтами - разные
    строки, и хэш от них разный.

    Откуда берётся разница: страница приходит из сети, проходит через стек
    HTTP и разборщик разметки, и каждый из них вправе нормализовать текст
    по-своему. Две реализации на разных языках получат из одной страницы разные
    байты одного и того же идентификатора.

    Args:
        text (str): Исходная строка.

    Returns:
        str: Та же строка в форме NFC.
    """
    return unicodedata.normalize("NFC", text)


def _reject(value: Any, where: str) -> None:
    """Отвергает значение, которое каноническая форма выразить не может.

    Args:
        value (Any): Значение.
        where (str): Путь до значения, для сообщения.

    Returns:
        None

    Raises:
        ValidationError: Всегда.
    """
    raise ValidationError(
        f"каноническая форма не выражает {type(value).__name__} однозначно "
        f"(путь {where}). Значение: {value!r}"
    )


def _prepare(value: Any, where: str) -> Any:
    """Готовит значение к сериализации: нормализует и проверяет.

    Args:
        value (Any): Значение любого поддерживаемого вида.
        where (str): Путь до значения, для сообщения об отказе.

    Returns:
        Any: Значение, годное для json.dumps в канонической форме.

    Raises:
        ValidationError: Если значение невыразимо: число с плавающей точкой,
            ключ не-строка, множество, произвольный объект.
    """
    if value is None or isinstance(value, bool):
        return value

    if isinstance(value, int):
        # Правило 7: целое выводится без дробной части и без экспоненты - так
        # json.dumps и делает. Правило 9 про -0 здесь не нужно: в Python -0
        # целое неотличимо от 0.
        return value

    if isinstance(value, float):
        # Правило 8. Отвергать, а не округлять: округление - это молчаливая
        # подмена значения, а её последствие всплывёт в чужом хэше через
        # неделю. Отдельно называем не-числа, потому что json.dumps пишет их
        # как NaN и Infinity - и получившийся файл перестаёт быть JSON, хотя
        # Python читает его обратно как ни в чём не бывало.
        if math.isnan(value) or math.isinf(value):
            raise ValidationError(
                f"каноническая форма запрещает {value!r} (путь {where}): "
                "JSON такого значения не знает, и файл с ним перестаёт быть "
                "разбираемым чем-либо, кроме Python"
            )
        raise ValidationError(
            f"каноническая форма запрещает числа с плавающей точкой "
            f"(путь {where}, значение {value!r}). У них нет единственного "
            "десятичного вида, и две реализации запишут их по-разному. "
            "Выразите величину целым: деньги - минорными единицами, время - "
            "миллисекундами"
        )

    if isinstance(value, str):
        return canonical_normalize(value)

    if isinstance(value, dict):
        prepared: dict[str, Any] = {}
        for key, item in value.items():
            if not isinstance(key, str):
                raise ValidationError(
                    f"каноническая форма требует строковых ключей "
                    f"(путь {where}, ключ {key!r}). Порядок ключей задан по "
                    "кодовым точкам, а у не-строки кодовых точек нет"
                )
            # Нормализация ДО сортировки, а не после: NFC меняет кодовые
            # точки, и порядок, снятый с ненормализованных ключей, разошёлся
            # бы с порядком, снятым с нормализованных.
            canonical_key = canonical_normalize(key)
            if canonical_key in prepared:
                raise ValidationError(
                    f"после нормализации ключи {key!r} и другой ключ совпали "
                    f"(путь {where}). Каноническая форма не решает, какой из "
                    "них оставить, - это должен решить вызывающий"
                )
            prepared[canonical_key] = _prepare(item, f"{where}.{canonical_key}")
        return prepared

    if isinstance(value, (list, tuple)):
        # Правило 4: порядок элементов значим и не сортируется.
        return [_prepare(item, f"{where}[{index}]") for index, item in enumerate(value)]

    _reject(value, where)
    return None


def canonical_dumps(value: Any) -> str:
    """Сериализует значение в каноническую форму.

    Выполняются правила 1-9 документа: UTF-8 без BOM, NFC, ключи по кодовым
    точкам, порядок массива сохраняется, никаких незначащих пробелов,
    минимальное экранирование, целые без экспоненты, никаких чисел с
    плавающей точкой, никакого -0.

    Args:
        value (Any): Значение: словарь, список, строка, целое, булево, None.

    Returns:
        str: Каноническое представление. Строка, а не байты: кодировка UTF-8
        применяется при записи, и делать это дважды незачем.

    Raises:
        ValidationError: Если значение невыразимо канонической формой.
    """
    return json.dumps(
        _prepare(value, "$"),
        ensure_ascii=False,
        sort_keys=True,
        separators=_SEPARATORS,
        allow_nan=False,
    )
