"""Чтение атрибута как наблюдаемого значения.

Файл появился по той же причине, что и `_host.py`: правило нашлось написанным в
трёх местах. Две копии были одинаковы дословно, третью я дописал сам - и она
разошлась с ними в первый же час, потому что различала на одно состояние больше.

Различает она вот что. Атрибута нет вовсе и атрибут есть, но пуст - разные вещи.
Первое означает «площадка не дала», второе - «площадка дала пустое», и обе
прежние копии сводили их в пустое значение. Для адреса разница видна глазом:
`<a href="">` перезагружает текущую страницу, а `<a>` без адреса ссылкой не
является вовсе.

Правило одно на весь пакет и живёт здесь.
"""

from __future__ import annotations

from selectolax.parser import HTMLParser, Node

from ._observed import Observed
from .extraction import SELECTORS

__all__ = ["attribute"]


def attribute(node: Node | None, name: str, field_name: str) -> Observed[str]:
    """Извлекает значение атрибута как наблюдаемое значение.

    Различаются три исхода, и все три вызывающему нужны. Селектор не нашёл узла:
    искать атрибут не у чего. Узел есть, атрибута нет: площадка его не дала.
    Атрибут есть и пуст: площадка дала пустое - факт о странице, а не о нашем
    незнании.

    Тип Observed обещает, что PRESENT - это непустое значение, и собирать его в
    состоянии, которое он сам себе запрещает, значит отбирать у вызывающего
    единственный способ отличить «адрес есть» от «атрибут пуст».

    Args:
        node (Node | None): Узел либо None, если селектор не нашёл ничего.
        name (str): Имя атрибута.
        field_name (str): Имя поля, попадающее в причину отсутствия.

    Returns:
        Observed[str]: Наблюдение. Причина отсутствия называет, какой из двух
        случаев произошёл: `selector_no_match:` либо `attribute_absent:`.
    """
    if node is None:
        return Observed.missing(f"selector_no_match:{field_name}")

    attributes = node.attributes or {}
    # Проверяется наличие ключа, а не значение по нему. Разборщик отдаёт None и
    # для атрибута без значения, и для пустого, так что .get() свёл бы «атрибута
    # нет» с «атрибут пуст» - ровно то различие, ради которого файл и написан.
    if name not in attributes:
        return Observed.missing(f"attribute_absent:{field_name}")

    raw = attributes[name]
    if raw is None:
        # `data-href` без значения и `data-href=""` разборщик не различает, и
        # различать их незачем: оба означают «атрибут есть, значения нет».
        return Observed.empty("")

    value = raw.strip()
    return Observed.present(value) if value else Observed.empty("")


def observe_locale(html: str) -> Observed[str]:
    """Читает локаль интерфейса со страницы.

    Локаль привязана к аккаунту, а не к адресу: запрос с префиксом /en/ отдаёт
    ту же страницу на том же языке. Переключить её запросом нельзя, и
    единственное, что остаётся, - узнать, какая она.

    Прежде не узнавали вовсе. Страница на чужой локали разбиралась молча, и
    вызывающий получал английские тексты, полагая их русскими: поля, которые
    приходят текстом - описание заказа, подпись времени, имя собеседника, -
    возвращаются на том языке, на котором их отдала площадка.

    Args:
        html (str): Разметка страницы.

    Returns:
        Observed[str]: Локаль либо причина, по которой её не видно. Три исхода
        различаются, как и у всякого чтения атрибута.
    """
    node = HTMLParser(html).css_first(SELECTORS["session.locale"])
    return attribute(node, "lang", "locale")
