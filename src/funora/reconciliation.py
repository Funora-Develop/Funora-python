r"""Сверка после неоднозначного исхода записи.

Файл порождён из спецификации, править его руками нельзя: правка исчезнет при
следующей сборке. Источник - spec/protocol/reconciliation.yaml в репозитории Funora-spec.
Перестроить: .venv\Scripts\python.exe tools/codegen.py

Сверка - ПРОЦЕДУРА НАБЛЮДЕНИЯ, а не петля управления. Она отвечает на
вопрос «что вышло из отправки» и ничего не предпринимает.

СВЕРКА НИКОГДА НЕ ОТПРАВЛЯЕТ ПОВТОРНО. Решение принимает вызывающий, и
только он: у отправленного сообщения нет отмены, и автоматика,
решающая за человека, однажды напишет покупателю дважды.

Вердикта отрицания здесь НЕТ. Отсутствие сообщения в истории -
свидетельство отрицательное, и объявлять по нему «не отправлено»
значило бы подтолкнуть вызывающего написать второй раз.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Final

__all__ = ["ReconcileVerdict", "RECONCILE_READS", "RECONCILE_DELAYS_MS"]


class ReconcileVerdict(StrEnum):
    """Чем окончилась сверка.

    delivered: Своё новое сообщение найдено в истории. Положительное свидетельство.

    absent_from_history: Чтение полное, признак себя показал себя, искомого сообщения
        нет.

    undetermined: Сверка ответа не дала. Честное незнание.

    """

    DELIVERED = "delivered"
    ABSENT_FROM_HISTORY = "absent_from_history"
    UNDETERMINED = "undetermined"


#: Сколько раз перечитывать историю.
RECONCILE_READS: Final[int] = 3

#: Паузы перед каждым чтением, миллисекунды.
#:
#: Числа ВЫБРАНЫ, а не наблюдены: ни одной записанной отправки не
#: пришлось сверять чтением - все подтверждались самим ответом канала.
RECONCILE_DELAYS_MS: Final[tuple[int, ...]] = (1000, 3000, 8000)
