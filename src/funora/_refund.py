"""Возврат средств покупателю: адрес и разбор ответа.

САМАЯ ОПАСНАЯ ИЗ НАПИСАННЫХ ОПЕРАЦИЙ. Деньги уходят покупателю, и площадка не
предлагает вернуть их обратно ничем. «Попробовать и посмотреть» здесь стоит
настоящих денег продавца.

ЧТО НАБЛЮДЕНО НАМИ, А ЧТО НЕТ. Наблюдён ЗАПРОС - целиком: адрес в атрибуте
формы, оба поля в ней же, и признак того, что площадка возврат по этому заказу
предлагает.

НЕ НАБЛЮДЁН ОТВЕТ. Что в нём приходит, известно от независимой реализации того
же протокола: объект с признаком отказа error и сообщением msg.

ОТСЮДА ОТКАЗ ЧИТАТЬ ОТВЕТ БЕЗ ПРИЗНАКА. Площадка отвечает признаком ОТКАЗА, а не
успеха; отсутствие поля означает не успех, а непонятный ответ.

У поднятия то же правило стоило суток ожидания при ошибке. Здесь оно стоит денег,
о судьбе которых вызывающий не узнает, - и потому отказ здесь громче.

СУММЫ ВОЗВРАТА НЕТ НИГДЕ - ни в запросе, ни в ответе. Сколько именно вернулось,
вызывающий узнаёт только чтением заказа.

Наблюдено нами 31.08.2026: order.v9.logged.ru, форма возврата и её поля.
Известно от FunPayAPI (FunPayCardinal, account.py, refund): состав ответа.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Any, Final

from .errors import ProtocolChangedError

__all__ = ["RefundResult", "parse_refund", "REFUND_PATH"]

#: Адрес возврата. Наблюдён НАМИ - в атрибуте action формы на странице заказа.
REFUND_PATH: Final[str] = "/orders/refund"


@dataclass(frozen=True, slots=True)
class RefundResult:
    """Исход возврата средств покупателю.

    Attributes:
        refunded (bool): Состоялся ли возврат. Читается ОТРИЦАНИЕМ признака
            отказа: площадка отвечает признаком отказа, а не успеха.
        message (str): Сообщение площадки человеку, как есть. Не разбирается:
            это текст на локали интерфейса, а причина здесь про деньги.
        order_id (str): Заказ, по которому просили возврат.
        observed_at (datetime): Момент получения ответа.
    """

    refunded: bool
    message: str
    order_id: str
    observed_at: datetime


def parse_refund(payload: Any, *, order_id: str, observed_at: datetime) -> RefundResult:
    """Разбирает ответ площадки на возврат.

    ПРИЗНАК ОТКАЗА ОБЯЗАТЕЛЕН. Без него неизвестно, ушли деньги или нет, а
    повторить, чтобы выяснить, нельзя: повтор здесь - второй возврат.

    Аргументы:
        payload (Any): Разобранное тело ответа.
        order_id (str): Заказ, по которому просили возврат.
        observed_at (datetime): Момент получения.

    Возвращает:
        RefundResult: Исход.

    Raises:
        ProtocolChangedError: Если в ответе нет признака отказа.
    """
    if not isinstance(payload, dict):
        raise ProtocolChangedError(
            f"ответ на возврат не объект, а {type(payload).__name__}. Что "
            f"случилось с деньгами по заказу {order_id} - неизвестно; прочитайте "
            "заказ и посмотрите"
        )

    error = payload.get("error")
    # Логическое требуется строго. Истина в Python - это единица, и error=1
    # прочиталось бы как отказ, а error=0 как успех, ни разу не будучи
    # логическим. У денег такая подмена стоит дороже всего.
    if not isinstance(error, bool):
        raise ProtocolChangedError(
            f"в ответе на возврат по заказу {order_id} нет признака отказа error. "
            "Площадка отвечает признаком ОТКАЗА, а не успеха, и без него исход "
            "неизвестен. Деньги МОГЛИ уйти покупателю: прочитайте заказ и "
            "посмотрите, а повторять не надо - повтор здесь второй возврат"
        )

    raw_message = payload.get("msg")
    return RefundResult(
        refunded=not error,
        message=raw_message if isinstance(raw_message, str) else "",
        order_id=order_id,
        observed_at=observed_at,
    )
