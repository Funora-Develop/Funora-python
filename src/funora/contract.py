r"""Версия контракта, которую реализует пакет.

Файл порождён из спецификации, править его руками нельзя: правка исчезнет при
следующей сборке. Источник - spec/version.yaml в репозитории Funora-spec.
Перестроить: .venv\Scripts\python.exe tools/codegen.py

Три оси версий разведены намеренно. Версия спецификации говорит, какой
контракт реализован. Версия канонической формы меняется отдельно: одна
и та же модель может сериализоваться по-новому, и это ломает
сохранённые отпечатки и ключи гашения повторов.

Семейство адаптера отделяет состояние, снятое с одной площадки, от
состояния другой: совпадение идентификаторов было бы случайным, а
последствия - молчаливым гашением чужих событий.
"""

from __future__ import annotations

from typing import Final

__all__ = [
    "SPEC_VERSION",
    "SPEC_STATUS",
    "CANONICAL_FORM_VERSION",
    "RUNNER_PROTOCOL",
    "SUPPORTED_LOCALES",
    "ADAPTER_FAMILY",
]

#: Версия спецификации, которую реализует пакет.
SPEC_VERSION: Final[str] = "0.35.0"

#: Состояние спецификации: draft либо released.
#:
#: В состоянии draft контракт может меняться без соблюдения правил
#: совместимости, и классификация изменений носит осведомительный
#: характер.
SPEC_STATUS: Final[str] = "draft"

#: Версия правил канонической сериализации.
#:
#: Меняется отдельно от версии спецификации: одна и та же модель
#: может сериализоваться по-новому, и это ломает сохранённые
#: отпечатки и ключи гашения повторов.
CANONICAL_FORM_VERSION: Final[int] = 3

#: Версия протокола запуска набора соответствия.
RUNNER_PROTOCOL: Final[int] = 1

#: Локали интерфейса, для которых у проекта есть снимки страниц.
#:
#: Локаль привязана к аккаунту, а не к адресу, и переключить её
#: запросом нельзя. При локали вне перечня реализация обязана
#: вернуть типизированную ошибку, но никогда - пустой результат.
SUPPORTED_LOCALES: Final[tuple[str, ...]] = (
    "ru",
    "en",
)

#: Семейство протокольного адаптера.
#:
#: Состояние, снятое с другой площадки, бессмысленно здесь целиком:
#: совпадение идентификаторов было бы случайным, а последствия -
#: молчаливым гашением чужих событий.
ADAPTER_FAMILY: Final[str] = "funpay-web"
