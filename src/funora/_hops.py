"""Решение о следующем переходе, отделённое от способа сходить в сеть.

Модуль появился ради асинхронного транспорта. Без него правило переходов
пришлось бы написать второй раз - а именно оно однажды уже стоило сессионного
ключа, и оно же в проекте уже жило трижды и по-разному (см. [_host.py]).
Копия правила безопасности расходится ровно так же, как любая другая, но цена
расхождения здесь - чужой доступ к аккаунту.

Функция чистая: на вход - то, что видно в ответе, на выход - решение. Ни
синхронный, ни асинхронный транспорт не знают, как оно принято, и оба обязаны
поступить одинаково.

Решений три, и они не сводятся к двум.

``Stop`` - переходов больше нет либо исчерпан предел. Ответ, который на руках,
и есть конечный.

``Follow`` - переход проверен, секрет можно отправить дальше.

``Reject`` - переход уводит с ожидаемого хоста либо понижает схему. Запрос туда
не отправляется вовсе: проверка после отправки бесполезна, секрет уже ушёл бы.
Отвергнутый адрес всё равно объявляется конечным - это не мелочь, а разница
между диагнозом «нас пытались увести» и диагнозом «разметка изменилась».
"""

from __future__ import annotations

from dataclasses import dataclass
from urllib.parse import urljoin

from ._host import is_safe_hop

__all__ = ["Stop", "Follow", "Reject", "Hop", "next_hop"]


@dataclass(frozen=True, slots=True)
class Stop:
    """Переходов больше нет: ответ на руках конечный."""


@dataclass(frozen=True, slots=True)
class Follow:
    """Переход проверен и разрешён.

    Attributes:
        url (str): Адрес, по которому можно отправить запрос вместе с секретом.
    """

    url: str


@dataclass(frozen=True, slots=True)
class Reject:
    """Переход отвергнут: секрет туда не уходит.

    Attributes:
        url (str): Адрес, куда нас пытались увести. Объявляется конечным, чтобы
            классификатор увидел чужой хост и поставил диагноз wrong_identity, а
            не unknown по пустому телу.
    """

    url: str


#: Любое из трёх решений.
Hop = Stop | Follow | Reject


def next_hop(
    *,
    current: str,
    is_redirect: bool,
    location: str,
    redirects: int,
    max_redirects: int,
    expected: str,
) -> Hop:
    """Решает, что делать с полученным ответом.

    Args:
        current (str): Адрес, на который был отправлен запрос.
        is_redirect (bool): Является ли ответ перенаправлением.
        location (str): Значение заголовка Location. Пустая строка, если его нет.
        redirects (int): Сколько переходов уже выполнено.
        max_redirects (int): Предел числа переходов.
        expected (str): Ожидаемый хост площадки.

    Returns:
        Hop: Stop, Follow либо Reject.
    """
    if not is_redirect or redirects >= max_redirects:
        return Stop()
    if not location:
        # Перенаправление без адреса перехода. Идти некуда, и придумывать адрес
        # самим - последнее, чем стоит заниматься с секретом в руках.
        return Stop()

    target = urljoin(current, location)
    if not is_safe_hop(current, target, expected):
        return Reject(target)
    return Follow(target)
