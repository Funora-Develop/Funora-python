"""Структурный скелет страницы.

Фикстуры нужны, чтобы чинить парсер и ловить изменения разметки. Сохранять для
этого настоящий HTML со страницы под авторизацией нельзя: там имена покупателей,
тексты переписки, номера заказов. Редактирование такого HTML - подход, при котором
вопрос «достаточно ли сработала редакция» остаётся открытым навсегда, а git-историю
из форков и кэшей потом не вычистить.

Скелет решает это иначе: он сохраняет всё, что нужно для селекторов, и не может
содержать персональных данных.

Слово «не может» точно для текста и значений атрибутов: там сохраняется подпись,
а не значение, и обратного преобразования не существует. С путями в ссылках
правило разное для своего хоста и для чужого.

  * Структура сохраняется целиком: теги, вложенность, порядок, атрибут class.
  * Каждый текстовый узел заменяется подписью ``T{длина}:{классы символов}``.
  * Значение атрибута заменяется той же подписью с номером: ``T9:d#1``. Подпись
    остаётся на месте - по ней видно длину и состав, - а номер добавляет ровно
    одно сведение: два значения совпадают или нет. Без этого идентификатор
    диалога, лежащий в ``data-id``, схлопывал пятьдесят диалогов в одну подпись.
  * Строка запроса на своём хосте заменяется номером: ``/chat/?{q1}``. У диалога
    путь один на всех, и весь идентификатор сидит там.
  * Путь на своём хосте сохраняет форму, а сегменты с цифрами становятся
    ``{n1}``, ``{n2}`` и так далее: ``/orders/12345`` превращается в
    ``/orders/{n1}``. Видно, что это ссылка на заказ, и видно, тот же это заказ
    или другой, - но не видно какой. Номер выдаётся по первому появлению
    значения в пределах документа и между документами смысла не имеет.
  * Путь на чужом хосте маскируется целиком: ``t.me/ivanpetrov`` превращается в
    ``t.me/{t}``. Ссылки на чужие адреса пишут люди в переписке, и в них живёт
    то, ради чего их и пишут. Прежнее правило маскировало сегмент только при
    наличии цифр либо нелатинских знаков, и такое имя проходило дословно в
    снимок, который лежит в открытом репозитории. Схема и имя хоста остаются:
    они публичны и говорят, куда ведёт ссылка, не говоря, к кому.
  * Содержимое script и style выбрасывается целиком.
  * Результат остаётся разбираемым HTML: пустые элементы записываются парой
    тегов, и только настоящие void-теги - одиночным. Это позволяет применять
    скелет как фикстуру и проверять на нём селекторы тем же парсером, которым
    разбирается настоящая страница.

Классы символов в подписи: ``d`` цифры, ``a`` латиница, ``c`` кириллица,
``s`` пробельные, ``p`` пунктуация ASCII, ``o`` прочее.

Про нумерацию стоит знать три вещи, и все - про то, чего она НЕ делает.

Она не касается текстовых узлов. Граница проведена по различию «разметка против
содержимого»: равенство двух значений атрибута нужно проверкам, равенство двух
сообщений переписки не нужно никому, а сведением о переписке является.

Она не действует на чужих хостах. Там номер сам по себе был бы сведением о
третьем лице - «эти два сообщения ведут на один аккаунт», - а никакой проверке
он не нужен: ``t.me/{t}`` остаётся неразличимым всюду.

Она не связывает документы. Один и тот же заказ получает разные номера в двух
снимках, а разные заказы - одинаковые. Сравнивать снимки по номерам нельзя, и
это ловушка, которую вводит сам формат.
"""

