#: Хост площадки. Пути на нём сохраняют форму, на чужих маскируются целиком.
DEFAULT_OWN_HOST: Final[str] = "funpay.com"

#: Имя формата, записываемое в описание происхождения фикстуры.
#:
#: Версия 1 записывала пустые элементы как ``<div/>`` и потому не разбиралась
#: HTML-парсером. Версия 3 маскирует пути на чужих хостах целиком. Версия 4
#: нумерует подписи идентификаторов пути. Версия 5 распространяет нумерацию на
#: строку запроса и на значения атрибутов: без них пятьдесят диалогов страницы
#: оставались неразличимы - идентификатор диалога лежит и там, и там, но не в
#: пути.
#: Величина берётся из порождённого файла, а не пишется здесь: формат снимков -
#: общая проверочная база, и вторая реализация обязана строить такой же.
SKELETON_FORMAT: Final[str] = GENERATED_SKELETON_FORMAT

#: Версии, в которых идентификаторы различимы между собой.
#:
#: Нужны проверкам: снимок, снятый до нумерации, различимость восстановить не
#: может, и требовать её от него нечестно. Перечень объявлен спецификацией, а не
#: выведен из порядка версий - вывод по порядку сломался бы на первой же версии,
#: поднятой по другой причине.
NUMBERED_SKELETON_FORMATS: Final[frozenset[str]] = GENERATED_NUMBERED_FORMATS

#: Форматы, которые проект умеет читать.
#:
#: Перечень нужен потому, что снимок не преобразуется в v4 автоматически:
#: нумерация восстанавливает различимость только при захвате, а из уже
#: замаскированного файла исходные значения не вернуть. Файлы прежних версий
#: остаются пригодными для всего, что не зависит от различимости.
SUPPORTED_SKELETON_FORMATS: Final[frozenset[str]] = ACCEPTED_SKELETON_FORMATS

#: Атрибуты, значение которых обрабатывается как путь.
#:
#: data-href попал сюда не для красоты: ссылка на пользователя в списке заказов
#: лежит именно в нём, а не в href, и без разбора как пути она превращалась в
#: безликую подпись. Форма ``/users/{n}/`` говорит, куда ведёт ссылка, и не
#: говорит, на кого.
_URL_ATTRS: Final[frozenset[str]] = frozenset(
    {"href", "src", "action", "formaction", "data-url", "data-href"}
)

#: Атрибуты, значение которых сохраняется как есть.
_VERBATIM_ATTRS: Final[frozenset[str]] = frozenset({"class"})

#: Атрибуты, несущие метку языка.
#:
#: Сохраняются дословно, но только если значение вправду похоже на метку.
#: Метка языка говорит о странице, а не о человеке: «ru» не сообщает о продавце
#: ничего, чего не сообщал бы адрес площадки.
#:
#: Пока они маскировались, всякий снимок нёс в lang подпись, и разбор объявлял
#: по нему локаль неподдержанной - собственные фикстуры заставляли реализацию
#: говорить неправду.
_LANGUAGE_ATTRS: Final[frozenset[str]] = frozenset({"lang", "hreflang"})

#: Как выглядит метка языка по BCP 47.
_LANGUAGE_TAG: Final[re.Pattern[str]] = re.compile(r"^[A-Za-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$")

#: Теги, содержимое которых не сохраняется.
#:
#: Выбрасывается только содержимое, атрибуты сохраняются по общим правилам. Путь
#: в src обезличивается тем же преобразованием, что и остальные ссылки, поэтому
#: прятать его незачем, а знать, какие скрипты грузит страница, нужно: по их
#: путям обычно и виден адрес канала обновлений.
_OPAQUE_TAGS: Final[frozenset[str]] = frozenset({"script", "style", "noscript", "template"})

#: Теги, которые в HTML не имеют закрывающей пары.
#:
#: Список нужен затем, что запись ``<div/>`` в HTML не означает пустой элемент:
#: разбор откроет div и вложит в него весь остаток документа. Для script это ещё
#: хуже - его содержимое считается сырым текстом до закрывающего тега, которого
#: нет, и в дерево не попадает вообще ничего. Скелет обязан читаться тем же
#: парсером, что и страница, иначе он не годится ни в фикстуры, ни в проверку.
_VOID_TAGS: Final[frozenset[str]] = frozenset(
    {
        "area",
        "base",
        "br",
        "col",
        "embed",
        "hr",
        "img",
        "input",
        "link",
        "meta",
        "param",
        "source",
        "track",
        "wbr",
    }
)

#: Строгая форма подписи текстового узла.
#:
#: Проверка по этому выражению, а не по «начинается с T и содержит двоеточие»:
#: строка вида ``Total: 500`` подходит под нестрогое условие и прошла бы
#: самопроверку как подпись, унеся с собой настоящий текст страницы.
_SIGNATURE_RE: Final[re.Pattern[str]] = re.compile(r"^T[1-9][0-9]*:[dacspo]+$")

#: Подпись сегмента пути, содержащего цифры.
_SEG_NUM: Final[str] = "{n}"

#: Подпись сегмента пути, содержащего символы вне латиницы.
_SEG_TEXT: Final[str] = "{t}"

_RE_LATIN = re.compile(r"[A-Za-z]")
_RE_DIGIT = re.compile(r"[0-9]")

#: Признак того, что сегмент пути - идентификатор, а не слово маршрута.
#:
#: Цифра либо ЗАГЛАВНАЯ буква. Второе заведено версией v6: идентификаторы
#: площадки - восемь заглавных латинских букв без единой цифры, и первый же
#: снимок страницы отдельного заказа принёс /orders/SBVZKXAF/ дословно.
#:
#: Граница проведена по регистру потому, что слова маршрута пишутся строчными по
#: соглашению об адресах. Ошибаться правило будет в сторону лишней маскировки, и
#: это верная сторона.
_RE_OPAQUE = re.compile(r"[0-9A-Z]")


class SkeletonError(ValidationError):
    """Скелет не удалось построить или он не прошёл самопроверку.

    Наследуется от ValidationError, а не от встроенной ошибки языка. Прежде
    здесь стоял RuntimeError, при том что класс экспортирован публично и
    возникает у всякого, кто зовёт skeletonize: общий перехват FunoraError его
    не ловил, и самопроверка, спасающая от утечки настоящего текста в снимок,
    роняла процесс целиком вместо того, чтобы отдать отказ.

    ValidationError - потому что произведённое значение непригодно: скелет,
    не прошедший самопроверку, публиковать нельзя.
    """


def _char_class(ch: str) -> str:
    """Определяет класс одного символа.

    Args:
        ch (str): Символ.

    Returns:
        str: Односимвольный код класса: d, a, c, s, p или o.
    """
    if ch.isspace():
        return "s"
    if ch.isdigit():
        return "d"
    if "A" <= ch <= "Z" or "a" <= ch <= "z":
        return "a"
    if "Ѐ" <= ch <= "ӿ":
        return "c"
    if ch.isascii() and not ch.isalnum():
        return "p"
    return "o"


def text_signature(text: str) -> str:
    """Строит подпись текстового узла.

    Подпись сохраняет длину и состав текста, но не сам текст. Этого достаточно,
    чтобы заметить изменение разметки и написать селектор, и недостаточно, чтобы
    восстановить содержимое.

    Args:
        text (str): Исходный текст узла.

    Returns:
        str: Подпись вида ``T14:dps`` или пустая строка, если текст состоит
        только из пробельных символов.
    """
    stripped = text.strip()
    if not stripped:
        return ""
    normalized = unicodedata.normalize("NFC", stripped)
    classes = "".join(sorted({_char_class(c) for c in normalized}))
    return f"T{len(normalized)}:{classes}"


def mask_path(
    value: str,
    own_host: str = DEFAULT_OWN_HOST,
    ordinals: dict[str, int] | None = None,
) -> str:
    """Обезличивает значение атрибута, содержащего путь.

    Правило разное для своего хоста и для чужого, и разница не в осторожности.

    На своём хосте форма пути сохраняется: по ней узнаётся назначение ссылки,
    а сегменты состоят из служебных слов площадки. Идентификатор заменяется
    подписью, и признак его - цифра либо заглавная буква: идентификаторы
    площадки бывают и вовсе без цифр, восемью заглавными латинскими буквами.

    На чужом хосте маскируется весь путь. Ссылки на чужие адреса пишут люди в
    переписке, и в них живёт то, ради чего их и пишут: ``t.me/ivanpetrov``,
    ``vk.com/durov``. Прежнее правило маскировало сегмент, только если в нём
    были цифры либо нелатинские знаки, - и такое имя проходило дословно в
    снимок, который лежит в открытом репозитории. Имя хоста при этом остаётся:
    оно публично и говорит, куда ведёт ссылка, не говоря, к кому.

    Подпись идентификатора нумеруется в пределах документа: одинаковые значения
    получают один номер, разные - разные. Без номеров восемь заказов на странице
    неразличимы, и всякая проверка, опирающаяся на различимость, проходит
    впустую, выглядя пройденной. Номер не раскрывает значения - он говорит
    только, совпадают ли два.

    Нумерация действует внутри одного документа и между документами смысла не
    имеет: ``{n1}`` в двух снимках - разные вещи.

    Args:
        value (str): Исходное значение атрибута.
        own_host (str): Хост площадки. Пути на нём сохраняют форму.
        ordinals (dict[str, int] | None): Таблица номеров документа, общая для
            всех его путей. None означает разовую маскировку вне документа: там
            нумеровать не с чем и подпись остаётся безномерной.

    Returns:
        str: Обезличенный путь.
    """
    if not value:
        return value

    body = value
    raw_query = ""
    if "?" in body:
        body, _, raw_query = body.partition("?")

    host = urlparse(body).hostname
    foreign = host is not None and not same_host(body, own_host)

    query = ""
    if raw_query:
        # На своём хосте строка запроса нумеруется: именно в ней лежит
        # идентификатор диалога, и без номера пятьдесят диалогов страницы
        # неразличимы - ровно та беда, ради которой нумерация и заведена.
        # На чужом не нумеруется по той же причине, что и путь: там совпадение
        # само по себе сведение о третьем лице.
        number = None if foreign else _ordinal(raw_query, "query", ordinals)
        query = "?{q}" if number is None else f"?{{q{number}}}"

    parts = body.split("/")
    out: list[str] = []
    for index, part in enumerate(parts):
        if not part:
            out.append(part)
            continue
        # Схема и имя хоста сохраняются всегда: они публичны и говорят, куда
        # ведёт ссылка, не говоря, к кому. Схема нужна отдельно - по ней видно,
        # защищено ли соединение.
        if index == 0 and part.endswith(":"):
            out.append(part)
            continue
        if foreign and host is not None and part.lower().split(":")[0] == host:
            out.append(part)
            continue
        if foreign:
            out.append(_SEG_TEXT)
            continue
        if _RE_OPAQUE.search(part):
            out.append(_numbered(part, ordinals))
        elif not part.isascii():
            out.append(_SEG_TEXT)
        else:
            out.append(part)
    return "/".join(out) + query


def _ordinal(value: str, kind: str, ordinals: dict[str, int] | None) -> int | None:
    """Выдаёт номер значения в пределах документа.

    Номер выдаётся по первому появлению и повторно не выдаётся: два вхождения
    одного значения получают один номер, два разных - разные. Само значение
    никуда не попадает: таблица живёт в памяти и выбрасывается вместе с
    документом.

    Разряды нумеруются раздельно. Совпадение номера пути с номером атрибута
    ничего не значило бы и только вводило бы в заблуждение: путь и подпись -
    разные пространства значений.

    Args:
        value (str): Исходное значение.
        kind (str): Разряд нумерации: путь, строка запроса, атрибут.
        ordinals (dict[str, int] | None): Таблица номеров документа либо None,
            если маскируется отдельное значение вне документа.

    Returns:
        int | None: Номер либо None, если нумеровать не с чем.
    """
    if ordinals is None:
        return None
    key = f"{kind}\x1f{value}"
    if key not in ordinals:
        # Номер отсчитывается внутри разряда, а не сквозным счётчиком: сквозной
        # выдал бы заказу номер 7 только потому, что до него встретилось шесть
        # чужих значений, и перестановка разметки меняла бы все номера сразу.
        ordinals[key] = sum(1 for name in ordinals if name.startswith(f"{kind}\x1f")) + 1
    return ordinals[key]


def _numbered(part: str, ordinals: dict[str, int] | None) -> str:
    """Возвращает подпись сегмента пути с номером в пределах документа.

    Args:
        part (str): Исходный сегмент пути.
        ordinals (dict[str, int] | None): Таблица номеров документа.

    Returns:
        str: Подпись вида ``{n3}`` либо безномерная ``{n}``.
    """
    number = _ordinal(part, "path", ordinals)
    return _SEG_NUM if number is None else f"{{n{number}}}"


def _mask_attr(name: str, value: str, ordinals: dict[str, int]) -> str:
    """Обезличивает значение произвольного атрибута.

    Args:
        name (str): Имя атрибута в нижнем регистре.
        value (str): Исходное значение.
        ordinals (dict[str, int]): Таблица номеров документа.

    Returns:
        str: Значение, пригодное для хранения в репозитории.
    """
    if name in _VERBATIM_ATTRS:
        return value
    if name in _LANGUAGE_ATTRS and _LANGUAGE_TAG.match(value.strip()):
        # Условие про форму существенно: атрибут обычный, и положить в него
        # можно что угодно. Дословно сохраняется лишь то, что вправду похоже на
        # метку языка, остальное маскируется по общему правилу.
        return value.strip()
    if name in _URL_ATTRS:
        return mask_path(value, DEFAULT_OWN_HOST, ordinals)
    if not value:
        return value
    sig = text_signature(value)
    if not sig:
        return ""
    # К подписи атрибута добавляется номер. Подпись остаётся на месте: по ней
    # видно длину и состав, и терять их нельзя - именно на длинах строились
    # выводы о позициях сообщений. Номер добавляет ровно одно сведение: два
    # значения совпадают или нет.
    #
    # На текстовые узлы это не распространяется. Атрибут - разметка, текст -
    # содержимое; равенство двух сообщений переписки никакой проверке не нужно,
    # а сведением о переписке является.
    number = _ordinal(value, f"attr:{name}", ordinals)
    return sig if number is None else f"{sig}#{number}"


def _render(node: Node, out: list[str], depth: int, ordinals: dict[str, int]) -> None:
    """Рекурсивно записывает узел в выходной буфер.

    Args:
        node (Node): Узел документа.
        out (list[str]): Буфер строк результата.
        depth (int): Текущая глубина вложенности, для отступов.
        ordinals (dict[str, int]): Таблица номеров документа. Общая на весь
            обход: номер выдаётся по первому появлению значения, и порядок
            обхода делает нумерацию повторяемой.

    Returns:
        None: Результат накапливается в out.
    """
    tag = node.tag
    pad = "  " * depth

    if tag == "-text":
        sig = text_signature(node.text_content or "")
        if sig:
            out.append(f"{pad}{sig}")
        return

    if tag in ("-comment", "_comment"):
        return

    attrs = node.attributes or {}
    rendered: list[str] = []
    for name in sorted(attrs):
        raw = attrs[name]
        if raw is None:
            rendered.append(name)
            continue
        masked = _mask_attr(name.lower(), raw, ordinals)
        rendered.append(f'{name}="{masked}"')

    head = tag if not rendered else tag + " " + " ".join(rendered)

    if tag in _OPAQUE_TAGS:
        out.append(f"{pad}<{head}></{tag}>")
        return

    children = list(node.iter(include_text=True))
    if not children:
        if tag in _VOID_TAGS:
            out.append(f"{pad}<{head}/>")
        else:
            out.append(f"{pad}<{head}></{tag}>")
        return

    out.append(f"{pad}<{head}>")
    for child in children:
        _render(child, out, depth + 1, ordinals)
    out.append(f"{pad}</{tag}>")


def _self_check(skeleton: str) -> None:
    """Проверяет, что в скелете не осталось человекочитаемого текста.

    Самопроверка нужна, потому что скелет строится обходом дерева, а дерево
    приходит от стороннего парсера: изменение его поведения не должно тихо
    превратить безопасный формат в небезопасный.

    Args:
        skeleton (str): Готовый скелет.

    Raises:
        SkeletonError: Если найдена последовательность, похожая на текст.
    """
    for line in skeleton.splitlines():
        body = line.strip()
        if not body:
            # Пустая строка появляется у сохранённого снимка в конце файла.
            # Без этого условия готовую фикстуру нельзя перепроверить тем же
            # кодом, которым она построена, - а перепроверять её придётся при
            # каждой смене формата.
            continue
        if _SIGNATURE_RE.match(body):
            continue
        if not body.startswith("<"):
            raise SkeletonError(f"строка не является ни подписью, ни тегом: {body[:60]}")
        if any("Ѐ" <= ch <= "ӿ" for ch in body):
            raise SkeletonError(f"кириллица в структурной строке: {body[:60]}")


def skeletonize(html: str) -> str:
    """Строит структурный скелет страницы.

    Args:
        html (str): Исходный HTML страницы.

    Returns:
        str: Скелет: дерево тегов с подписями текстовых узлов вместо текста.

    Raises:
        SkeletonError: Если разбор не удался или самопроверка нашла текст.
    """
    if not html or not html.strip():
        raise SkeletonError("пустой документ")

    try:
        tree = HTMLParser(html)
    except Exception as exc:
        raise SkeletonError("документ не разбирается как HTML") from exc

    root = tree.root
    if root is None:
        raise SkeletonError("документ не содержит корневого узла")

    out: list[str] = []
    # Таблица номеров создаётся на документ и живёт только во время обхода.
    # Значений она не сохраняет никуда: нумерация нужна затем, чтобы по снимку
    # было видно, какие ссылки совпадают, а какие нет.
    _render(root, out, 0, {})
    skeleton = "\n".join(out) + "\n"
    _self_check(skeleton)
    return skeleton
