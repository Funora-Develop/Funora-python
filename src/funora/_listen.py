"""Быстрый сигнал канала обновлений: узнать за секунды, что что-то изменилось.

ЧТО ЗДЕСЬ РЕШАЕТСЯ. Наблюдение читало две полные страницы на каждом шаге и
узнавало об изменении не раньше следующего чтения - от трёх секунд при
активности до двух минут в тишине. Площадка держит собственный канал с
промежутком в пять секунд, и он отвечает малым телом, когда менять нечего.

ГЛАВНОЕ РЕШЕНИЕ, И ОНО НЕ ПРО СКОРОСТЬ. Канал здесь - СИГНАЛ, а не источник
данных. Из ответа берётся ровно одно: изменилось что-нибудь или нет. Изменилось
- страницы читаются тем же кодом, что и прежде, и события собираются из них же.

Почему так, а не «читать данные прямо из канала». Канал отдаёт счётчики числами
и готовую разметку сообщений, и соблазн собирать события прямо из него велик. Но
поведения канала в двух случаях - при истёкшей сессии и при исчерпании предела -
не наблюдал никто. Реализация, собирающая события из его данных, обязана была бы
верить ему и в этих двух случаях тоже.

Сигналом же верить ему не нужно ВОВСЕ. Ошибётся в сторону «изменилось» - лишнее
чтение страниц, то есть ровно то, что было раньше. Ошибётся в сторону «тихо» -
это ловится сторожевым сроком: молчание дольше него означает не тишину, а
непонятность, и наблюдение возвращается к опросу страниц.

ЧЕГО ЭТО НЕ ДЕЛАЕТ. Пропущенное за простой по-прежнему не восстанавливается:
повтор по позиции не наблюдён, и метка отвечает на «изменилось ли», а не «что
именно я пропустил». Канал ускоряет обнаружение, а полноту по-прежнему даёт
чтение страниц.
"""

