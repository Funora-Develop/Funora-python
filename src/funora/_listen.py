#: Вид объекта со счётчиками покупок и продаж.
#:
#: Наблюдён и в подписке, и в ответе. В ответе несёт buyer и seller целыми - то
#: есть счётчик непрочитанного получается прямо, а не выводится из расхождения
#: двух позиций разметки.
ORDERS_COUNTERS: Final[str] = "orders_counters"

#: Вид объекта со счётчиками переписки.
#:
#: Наблюдён и в подписке, и в ответе. В ответе несёт counter и message целыми
#: плюс массив order длиной в число диалогов.
CHAT_BOOKMARKS: Final[str] = "chat_bookmarks"

#: С каким промежутком опрашивать канал.
#:
#: Пять секунд - СОБСТВЕННЫЙ темп площадки, наблюдённый, а не выбранный нами:
#: spec/extraction/updates.yaml, interval_s. Опрашивать чаще - ходить к каналу
#: чаще, чем ходит его же страница, то есть выделяться темпом без выигрыша:
#: ответ всё равно соберётся не раньше, чем площадка его обновит.
CHANNEL_INTERVAL_MS: Final[int] = 5000

#: Сколько не трогать канал после того, как он ответил непонятным.
#:
#: Минута, и она не про вежливость. Отказ канала бывает разовым - сеть моргнула,
#: - и бывает состоянием: истёкшая сессия, исчерпанный предел. Различить их в
#: момент отказа нечем, потому что ни того, ни другого никто не наблюдал.
#:
#: Пробовать снова сразу означало бы стучаться в отказывающую точку четыре раза
#: в минуту всё время, пока держится состояние. Ждать долго - терять скорость
#: там, где отказ был разовым. Минута - середина, и цена ошибки в обе стороны
#: здесь одна: опрос страниц, то есть прежнее поведение.
CHANNEL_COOLDOWN_MS: Final[int] = 60_000

#: Как долго доверять тишине канала, прежде чем перечитать страницы всё равно.
#:
#: СТОРОЖЕВОЙ СРОК - ТО, ЧТО ДЕЛАЕТ ВСЮ ЗАТЕЮ БЕЗОПАСНОЙ. Канал, замолчавший не
#: потому, что менять нечего, а потому, что перестал отвечать по существу, от
#: тишины неотличим: в обоих случаях объектов в ответе нет.
#:
#: Две минуты выбраны не наугад: это ПРЕЖНИЙ потолок интервала опроса
#: (SCHEDULING.max_interval_ms). Тем самым худший случай нового поведения ровно
#: равен обычному старому: даже канал, врущий тишину постоянно, не делает
#: наблюдение медленнее, чем оно было до него.
CHANNEL_WATCHDOG_MS: Final[int] = 120_000

#: Сколько непонятных ответов подряд считать состоянием, а не случайностью.
_FAILURES_BEFORE_COOLDOWN: Final[int] = 2


class ChannelSignal(Enum):
    """Что канал сказал о изменениях.

    Attributes:
        CHANGED: Что-то изменилось, страницы надо прочитать сейчас.
        QUIET: Изменений нет, чтение страниц можно пропустить.
        DEGRADED: Канал непригоден, дальше работает опрос страниц.
    """

    CHANGED = "changed"
    QUIET = "quiet"
    DEGRADED = "degraded"


@dataclass
class ChannelState:
    """Состояние слушателя канала между шагами.

    Attributes:
        tags (dict[tuple[str, str], str]): Метки по объектам, НАКОПЛЕННЫЕ за все
            ответы. Накопление обязательно: ответ несёт только изменившиеся
            объекты, и метки молчавших в нём нет вовсе.
        failures (int): Сколько непонятных ответов подряд.
        cooling_until (float): До какого момента монотонных секунд канал не
            трогать. Ноль означает, что канал доступен.
        quiet_since (float | None): С какого момента канал не приносил
            изменений. None означает, что тишины ещё не было.
        reason (str): Отчего канал признан непригодным в последний раз.
        degraded_announced (bool): Сказали ли уже вызывающему о переходе к
            опросу страниц. Одно событие на один переход, а не на каждый шаг.
    """

    tags: dict[tuple[str, str], str] = field(default_factory=dict)
    failures: int = 0
    cooling_until: float = 0.0
    quiet_since: float | None = None
    reason: str = ""
    degraded_announced: bool = False

    def available(self, now: float) -> bool:
        """Говорит, можно ли сейчас обращаться к каналу.

        Args:
            now (float): Текущий момент, монотонные секунды.

        Returns:
            bool: True, если остывание кончилось.
        """
        return now >= self.cooling_until

    def note_failure(self, reason: str, now: float) -> bool:
        """Записывает непонятный ответ и решает, уходить ли в остывание.

        ОДИН ОТКАЗ - ЕЩЁ НЕ СОСТОЯНИЕ. Сеть моргает, и уходить с быстрого пути
        на минуту из-за одного моргания значило бы терять скорость чаще, чем
        нужно. Два подряд - уже похоже на состояние.

        Args:
            reason (str): Машиночитаемая причина.
            now (float): Текущий момент, монотонные секунды.

        Returns:
            bool: True, если канал переведён в остывание этим отказом.
        """
        self.failures += 1
        self.reason = reason
        if self.failures < _FAILURES_BEFORE_COOLDOWN:
            return False
        self.cooling_until = now + CHANNEL_COOLDOWN_MS / 1000
        self.quiet_since = None
        return True

    def note_success(self, now: float, *, changed: bool) -> None:
        """Записывает понятный ответ.

        Args:
            now (float): Текущий момент, монотонные секунды.
            changed (bool): Принёс ли ответ изменения.

        Returns:
            None
        """
        self.failures = 0
        self.reason = ""
        self.degraded_announced = False
        self.quiet_since = None if changed else (self.quiet_since or now)

    def watchdog_expired(self, now: float) -> bool:
        """Говорит, что тишина канала длится дольше сторожевого срока.

        Тишина здесь не доказательство отсутствия изменений: канал, перестающий
        отвечать по существу, выглядит точно так же. По истечении срока страницы
        читаются независимо от того, что сказал канал.

        Args:
            now (float): Текущий момент, монотонные секунды.

        Returns:
            bool: True, если пора перечитать страницы всё равно.
        """
        if self.quiet_since is None:
            return False
        return (now - self.quiet_since) * 1000 >= CHANNEL_WATCHDOG_MS


def wanted_objects(own_user_id: str) -> list[tuple[str, str]]:
    """Перечисляет объекты, на которые подписывается наблюдение.

    ДВА, А НЕ N. Подписаться можно и на каждый диалог порознь, но объектов в
    подписке принимается десять, а обрезка молчалива: продавец с пятнадцатью
    диалогами не узнал бы, что пять из них не слушаются вовсе.

    Эти два объекта - глобальные счётчики аккаунта, и их ровно столько же при
    одном диалоге и при тысяче. Ответ по ним говорит «в продажах что-то
    изменилось» и «в переписке что-то изменилось», а что именно - выяснит
    чтение страниц, которое и без канала умеет это точно.

    Args:
        own_user_id (str): Собственный идентификатор, он же идентификатор обоих
            объектов подписки: наблюдено, что оба берут id из data-user.

    Returns:
        list[tuple[str, str]]: Вид и идентификатор по объекту.
    """
    return [(ORDERS_COUNTERS, own_user_id), (CHAT_BOOKMARKS, own_user_id)]


def seed_tags(context: RunnerContext) -> dict[tuple[str, str], str]:
    """Берёт со страницы те метки, которые на ней вправду видно.

    ЧТО ЗДЕСЬ НАБЛЮДЕНО, А ЧТО НЕТ, и почему это не мешает.

    Метка orders_counters наблюдена: она РАВНА значению data-orders, сверено в
    живой вкладке 29.08.2026.

    Метка chat_bookmarks не наблюдена. Кандидат - data-bookmarks-tag того же
    узла - объявлен носителем метки подписки, но в перечень сверки не входил.
    Он берётся здесь, и вот почему это безопасно: НЕУГАДАННАЯ МЕТКА НЕ ЛОМАЕТ
    НИЧЕГО. Площадка принимает любую, в том числе выдуманную, и отвечает на неё
    всем, что изменилось, - наблюдено 30.08.2026. То есть худший исход ошибки
    здесь - один лишний полный ответ на первом опросе, после которого настоящая
    метка приезжает в ответе и накапливается.

    Ненаблюдённого поля не берётся: у объекта без метки её место займёт
    UNSEEN_TAG при сборке подписки, и это тот же самый безопасный исход.

    Args:
        context (RunnerContext): Что прочитано со страницы.

    Returns:
        dict[tuple[str, str], str]: Метки, годные для первой подписки.
    """
    if not context.own_user_id.is_observed:
        return {}

    own = context.own_user_id.value
    tags: dict[tuple[str, str], str] = {}
    if context.orders_tag.is_observed and context.orders_tag.value:
        tags[(ORDERS_COUNTERS, own)] = context.orders_tag.value
    if context.bookmarks_tag.is_observed and context.bookmarks_tag.value:
        tags[(CHAT_BOOKMARKS, own)] = context.bookmarks_tag.value
    return tags


def classify_signal(answer: UpdatesAnswer) -> tuple[ChannelSignal, str]:
    """Решает, что ответ канала означает для наблюдения.

    ПОРЯДОК ШАГОВ ВАЖЕН, и он тот же, что у разбора ответа на отправку: сперва
    объявленная ошибка, потом содержимое. Ответ с непустой ошибкой и пустыми
    объектами иначе прочитался бы тишиной - то есть отказ выглядел бы
    подтверждением, что менять нечего.

    Args:
        answer (UpdatesAnswer): Разобранный ответ канала.

    Returns:
        tuple[ChannelSignal, str]: Сигнал и машиночитаемая причина. Причина
        пуста, когда объяснять нечего.
    """
    if answer.error is not None:
        # Что именно площадка кладёт в это поле при неудаче, не наблюдал никто:
        # пустым оно наблюдалось, непустым - ни разу. Поэтому непустое читается
        # как «канал непригоден», а не толкуется по содержимому.
        return ChannelSignal.DEGRADED, "channel_reported_error"

    if answer.is_quiet:
        return ChannelSignal.QUIET, ""

    return ChannelSignal.CHANGED, ""


def unexpected_shape(answer: UpdatesAnswer) -> str:
    """Называет то, чего в ответе быть не должно.

    Опрос идёт БЕЗ ДЕЙСТВИЯ, и площадка отвечает на такой запрос логическим, а
    не объектом - наблюдено. Объект в ответе означает, что мы получили ответ на
    чужой запрос либо канал устроен не так, как наблюдался.

    Ответ на это не «разобрать поаккуратнее», а вернуться к опросу страниц:
    страницы читаются кодом, чьё поведение установлено.

    Args:
        answer (UpdatesAnswer): Разобранный ответ канала.

    Returns:
        str: Причина непригодности либо пустая строка, если ответ ожидаемый.
    """
    if answer.answered_action:
        return "channel_answered_an_action_we_did_not_send"
    return ""
