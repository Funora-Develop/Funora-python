"""Превращение вердикта классификатора в ошибку.

Отображение живёт в спецификации и порождается, а не пишется: от него зависит,
повторит клиент запрос или остановится навсегда. Здесь только то, что таблицей
не выражается, - три уточнения, зависящие от состояния клиента, а не от ответа.

Первое. Истёкшая сессия и неверный секрет выглядят одинаково, а лечатся
по-разному: первую имеет смысл обновить и повторить, второй повторять
бессмысленно, и попытка обновления только добавит подозрительных запросов к
аккаунту, который и так под вопросом. Различает их одно: подтверждалась ли
сессия хоть раз за время жизни клиента.

Второе. Вердикт, принятый непроверенной сигнатурой, ошибку поднимает - не
заметить настоящую страницу проверки опаснее, чем сработать по тексту, - но
признак непроверенности переносится в экземпляр. По такой ошибке нельзя
останавливаться навсегда: страницы, ради которой написана сигнатура, никто не
видел.

Третье. Пара, которой нет в таблице, означает, что классификатор вернул вердикт,
не предусмотренный спецификацией. Это не повод придумать ошибку на месте:
придуманная ошибка разойдётся между реализациями именно там, где расхождение
дороже всего.
"""

from __future__ import annotations

from ._classify import Verdict
from .errors import (
    FunoraError,
    InvalidCredentialsError,
    ProtocolChangedError,
    SessionExpiredError,
)
from .response_classes import VERDICT_ERRORS

__all__ = ["error_for", "PROVISIONAL_ATTR"]

#: Имя признака непроверенности на экземпляре ошибки.
#:
#: Признак живёт на экземпляре, а не на классе: непроверенность - свойство
#: конкретного решения, а не вида ошибки. Один и тот же ChallengeRequiredError
#: может быть поднят и по структурному признаку, и по догадке о тексте.
PROVISIONAL_ATTR = "provisional"


def error_for(
    verdict: Verdict,
    *,
    session_ever_valid: bool = False,
) -> FunoraError | None:
    """Возвращает ошибку, соответствующую вердикту.

    Args:
        verdict (Verdict): Вердикт классификатора.
        session_ever_valid (bool): Подтверждалась ли сессия хоть раз за время
            жизни клиента. Отличает истёкшую сессию от неверного секрета.

    Returns:
        FunoraError | None: Экземпляр ошибки либо None, если ответ пригоден для
        разбора. У экземпляра выставлен признак provisional, показывающий, было
        ли решение принято непроверенной сигнатурой.

    Raises:
        ProtocolChangedError: Если пара «класс, причина» отсутствует в таблице.
            Придумать ошибку на месте нельзя: придуманная разойдётся между
            реализациями.
    """
    key = (str(verdict.cls), verdict.reason)
    if key not in VERDICT_ERRORS:
        raise ProtocolChangedError(
            f"классификатор вернул вердикт {key}, которого нет в таблице "
            "соответствия. Либо таблица отстала от спецификации, либо появился "
            "новый класс ответа"
        )

    cls = VERDICT_ERRORS[key]
    if cls is None:
        return None

    # Уточнение, не выразимое таблицей: истёкшая сессия и неверный секрет
    # выглядят одинаково, но лечатся по-разному.
    if cls is SessionExpiredError and not session_ever_valid:
        cls = InvalidCredentialsError

    detail = f"{verdict.cls}: {verdict.reason}"
    if verdict.matched:
        detail += f" (сигнатура {verdict.matched})"

    error = cls(detail)
    setattr(error, PROVISIONAL_ATTR, verdict.provisional)
    return error  # type: ignore[return-value]
